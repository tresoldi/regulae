"""3-way synthetic tonogenesis fixture (cross-dimensional discovery validation).

**DATA**: 80 three-way cognate sets. Proto lect varies both initial
voicing and source tone freely. Two daughters both undergo
independent tonogenesis conditioned on proto's initial voicing
but with different outcomes:

- ``daughter_a``: voiceless → tone 1, voiced → tone 4
  (the same pattern as ``tone_chinese_like_clean/``)
- ``daughter_b``: voiceless → tone 2, voiced → tone 3
  (a different tonogenesis outcome on the same conditioning)

Expected output: ``MultiLectModel.cross_dimensional_table``
surfaces **four** committed rules (two per proto→daughter pair,
one for voiced and one for voiceless, both at confidence 1.0
after dual-framing dedup). Each rule is labelled with the
correct ``src_lect`` (proto) and ``tgt_lect`` (daughter_a or
daughter_b).

The daughter_a↔daughter_b pair has no tonogenesis structure
(both daughters were generated by direct rules from proto, so
conditionally on proto they are independent — the pairwise
alignment between them shouldn't commit any cross-dim rules
under the support/confidence floors).
"""

from __future__ import annotations

from pathlib import Path

from regulae import (
    CognateSet,
    Form,
    Segment,
    describe_cross_dimensional_rule,
    format_multi_lect_model,
    train_model,
)


def parse_toned_form(ipa: str) -> tuple[Segment, ...]:
    """Split off trailing tone digits and attach the tone to the
    last vowel. Same convention as ``tone_chinese_like_clean``."""
    i = len(ipa)
    while i > 0 and ipa[i - 1].isdigit():
        i -= 1
    segmental = ipa[:i]
    tone = ipa[i:] if i < len(ipa) else None

    vowels = set("aeiou")
    segments: list[Segment] = []
    tone_attached = False
    chars = list(segmental)
    for idx in range(len(chars) - 1, -1, -1):
        if not tone_attached and chars[idx] in vowels and tone:
            segments.insert(0, Segment(grapheme=chars[idx], tone=tone))
            tone_attached = True
        else:
            segments.insert(0, Segment(grapheme=chars[idx]))
    if tone and not tone_attached and segments:
        last = segments[-1]
        segments[-1] = Segment(grapheme=last.grapheme, tone=tone)
    return tuple(segments)


def load_corpus(path: Path) -> list[CognateSet]:
    corpus: list[CognateSet] = []
    with path.open() as f:
        header = f.readline().strip().split("\t")
        assert header == ["gloss", "proto", "daughter_a", "daughter_b"]
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) != 4:
                continue
            gloss, proto, a, b = parts
            corpus.append(
                CognateSet(
                    cognate_id=gloss,
                    forms={
                        "proto": Form(
                            lect_id="proto", segments=parse_toned_form(proto)
                        ),
                        "daughter_a": Form(
                            lect_id="daughter_a", segments=parse_toned_form(a)
                        ),
                        "daughter_b": Form(
                            lect_id="daughter_b", segments=parse_toned_form(b)
                        ),
                    },
                )
            )
    return corpus


def main() -> None:
    tsv_path = Path(__file__).parent / "cognates.tsv"
    corpus = load_corpus(tsv_path)
    print(f"Loaded {len(corpus)} 3-way synthetic tonogenesis sets.")
    print()
    print("Expected: 2 daughters each undergo independent tonogenesis")
    print("          on proto-initial-voicing, with different target tones.")
    print()

    model = train_model(corpus)
    print(format_multi_lect_model(model, top_unconditioned=10, top_conditioned=10))

    print()
    print("=" * 60)
    print(f"Multi-lect cross-dimensional rules: "
          f"{len(model.cross_dimensional_table.entries)}")
    print("=" * 60)
    for i, rule in enumerate(model.cross_dimensional_table.entries):
        print(
            f"#{i}: {rule.src_lect}[{rule.src_feature.feature}@{rule.src_position}] "
            f"→ {rule.tgt_lect}[{rule.tgt_dimension}={rule.tgt_value}"
            f"@{rule.tgt_position_offset:+d}]  "
            f"count={rule.count:.0f}/{rule.src_count:.0f}  "
            f"conf={rule.confidence:.2f}"
        )


if __name__ == "__main__":
    main()
